"""Maps every knowledge and skill line in the exam guide to where the course teaches it.

It scores each guide line against each section of the lessons by shared significant words,
plus exact exam terms. A low score is a prompt for a human to look, and not proof of a gap.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
GUIDE = pathlib.Path(sys.argv[1])
STOP = set("""the and for with that this from into when using use used than rather not are was were
been being their them they its it's which while each only such e.g via per both more most can may
might how why what who whom where before after about between across other all any also including
include includes includes required require requires need needs needed should would could will
implement implementing design designing designs choosing choose selecting select knowledge skills
providing provide provided understanding importance role value distinction difference risk risks
effective appropriate specific specifically particular given making make makes one two first based
has have had does do did but out over under within without through instead them even see""".split())
TERM = re.compile(r"`[^`]+`|[A-Za-z_][A-Za-z_./-]*[_./-][A-Za-z_./-]+|--?[a-z][a-z-]+|[A-Z][a-z]+[A-Z]\w+")


def words(text):
    return {w for w in re.findall(r"[a-z][a-z_-]{2,}", text.lower()) if w not in STOP}


def guide_lines():
    text = GUIDE.read_text(encoding="utf-8")
    text = text[text.index("6. Detailed Objectives by Domain"):text.index("7. How to Prepare")]
    text = text.replace("Claude Certification Program Exam guide\n", "")
    out, ts, kind, current = [], None, None, None
    for line in text.split("\n"):
        m = re.match(r"Task Statement (\d\.\d):", line)
        if m:
            if current:
                out.append(current)
                current = None
            ts = m.group(1)
            continue
        if line.startswith("Knowledge of"):
            kind = "K"
            continue
        if line.startswith("Skills in"):
            kind = "S"
            continue
        if line.startswith("Domain ") or not ts:
            continue
        if line.startswith("•"):
            if current:
                out.append(current)
            current = dict(ts=ts, kind=kind, text=line[1:].strip())
        elif current and line.strip():
            current["text"] += " " + line.strip()
    if current:
        out.append(current)
    return out


HOME = {"1.1": "06/b 06/a", "1.2": "06/f", "1.3": "06/f", "1.4": "06/h", "1.5": "06/h", "1.6": "06/a 06/f 12/e",
        "1.7": "06/g 12/d", "2.1": "06/c", "2.2": "06/e", "2.3": "06/c", "2.4": "06/d 06/e", "2.5": "12/a",
        "3.1": "12/b", "3.2": "12/c", "3.3": "12/b", "3.4": "12/d", "3.5": "12/d", "3.6": "12/e",
        "4.1": "03/b", "4.2": "03/b", "4.3": "03/c", "4.4": "03/c", "4.5": "03/e", "4.6": "12/e",
        "5.1": "03/f", "5.2": "06/h", "5.3": "06/f", "5.4": "06/g 12/d", "5.5": "10/c", "5.6": "05/d"}


def lesson(code):
    mod, letter = code.split("/")
    return next((ROOT / "02-modules").glob(f"{mod}-*/notes-{letter}.md"))


def main():
    rows = []
    for line in guide_lines():
        text = " ".join(lesson(c).read_text(encoding="utf-8") for c in HOME[line["ts"]].split()).lower()
        lwords = words(text)
        want = words(line["text"])
        missing = sorted(w for w in want if w not in lwords)
        terms = {t.strip("`").lower() for t in TERM.findall(line["text"])}
        lost = sorted(t for t in terms if t not in text)
        rows.append(dict(line, home=HOME[line["ts"]], frac=1 - len(missing) / max(1, len(want)),
                         missing=missing, lost=lost))
    return rows


if __name__ == "__main__":
    rows = main()
    extra = {"1.3": "AI13 L2", "1.5": "AI13 L2", "1.7": "AI13 L2", "2.4": "AI13 L3", "3.6": "AI13 L2",
             "4.3": "AI13 L3", "4.4": "AI13 L3", "5.4": "patched AI06 L7", "4.2": "patched AI03 L2"}
    out = ["# Exam Coverage Matrix", "",
           "Every Knowledge and Skills line in exam guide v1.0, section 6, with the lesson that teaches it. "
           "Generated by `scripts/audit_exam_coverage.py`.", "",
           "**Method and limits.** Lines were mapped to home lessons by task statement. `Words` is the share of "
           "the line's significant words found in those lessons, which is only a screening signal, because "
           "lessons paraphrase. `scripts/audit_exam_concepts.py` then searched for 75 specific concepts, "
           "and the weak results were read by hand. This wasn't a person rereading every line against every "
           "lesson.", "",
           "**Result.** All 30 task statements have a home lesson. Thin spots were patched in AI06 L7 "
           "(context degradation, scratchpads, summarize then spawn) and AI03 L2 (few-shot for hallucination "
           "and varied document structures). Gaps closed by new lessons: Agent SDK at reading level, CLI flags, "
           "Pydantic, MCP resources depth, exam technique, scenario walkthroughs and the guide's four exercises.",
           "", "| TS | Type | Guide line | Home | Also | Words |", "| --- | --- | --- | --- | --- | ---: |"]
    for r in rows:
        home = ", ".join(f"AI{c[:2]} L{ord(c[3]) - 96}" for c in r["home"].split())
        text = r["text"].replace("|", "/")
        out.append(f"| {r['ts']} | {r['kind']} | {text} | {home} | {extra.get(r['ts'], '')} | {100 * r['frac']:.0f}% |")
    target = ROOT / "01-source-map/EXAM_COVERAGE_MATRIX.md"
    target.write_text(chr(10).join(out) + chr(10), encoding="utf-8", newline=chr(10))
    print(len(rows), "guide lines written; lowest", min(r["frac"] for r in rows))
